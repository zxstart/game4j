package com.game4j.core.scanner;

import com.game4j.core.annotation.G4JController;
import io.github.classgraph.ClassGraph;
import io.github.classgraph.ClassInfo;
import io.github.classgraph.ClassInfoList;
import io.github.classgraph.ScanResult;

import java.util.ArrayList;
import java.util.Enumeration;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.net.URL;
import java.nio.charset.StandardCharsets;

/**
 * 控制器扫描器
 * <p>
 * 使用 ClassGraph 库扫描指定包下的所有带有 {@link G4JController} 注解的类。
 * </p>
 */
public class ControllerScanner {
    /**
     * Classpath resource generated by the game4j annotation processor.
     */
    public static final String INDEX_RESOURCE = "META-INF/game4j/controllers.idx";

    /**
     * Loads controller names from all generated indexes visible to the context class loader.
     * Unlike {@link #scan(String)}, this never walks jars or directories.
     */
    public static IndexedControllers loadIndex(String basePackage) {
        ClassLoader loader = contextClassLoader();
        Set<String> names = new LinkedHashSet<>();
        boolean found = false;
        try {
            Enumeration<URL> resources = loader.getResources(INDEX_RESOURCE);
            while (resources.hasMoreElements()) {
                found = true;
                URL resource = resources.nextElement();
                try (BufferedReader reader = new BufferedReader(new InputStreamReader(
                        resource.openStream(), StandardCharsets.UTF_8))) {
                    String name;
                    while ((name = reader.readLine()) != null) {
                        String candidate = name.trim();
                        if (!candidate.isEmpty() && !candidate.startsWith("#") && inPackage(candidate, basePackage)) {
                            names.add(candidate);
                        }
                    }
                }
            }
        } catch (IOException ex) {
            throw new IllegalStateException("Unable to load generated controller indexes", ex);
        }

        List<Class<?>> controllers = new ArrayList<>(names.size());
        for (String name : names) {
            try {
                controllers.add(Class.forName(name, false, loader));
            } catch (ClassNotFoundException ex) {
                throw new IllegalStateException("Generated controller index refers to a missing class: " + name, ex);
            }
        }
        return new IndexedControllers(found, List.copyOf(controllers));
    }
    /**
     * 扫描包并返回控制器类列表
     *
     * @param basePackage 基础包名
     * @return 控制器类列表
     */
    public static List<Class<?>> scan(String basePackage) {
        List<Class<?>> result = new ArrayList<>();
        try (ScanResult scanResult = new ClassGraph().enableAnnotationInfo().acceptPackages(basePackage).scan()) {
            ClassInfoList controllers = scanResult.getClassesWithAnnotation(G4JController.class.getName());
            for (ClassInfo classInfo : controllers) {
                result.add(classInfo.loadClass());
            }
        }
        return result;
    }

    private static boolean inPackage(String className, String basePackage) {
        return basePackage == null || basePackage.isBlank()
                || className.equals(basePackage)
                || className.startsWith(basePackage + ".");
    }

    private static ClassLoader contextClassLoader() {
        ClassLoader loader = Thread.currentThread().getContextClassLoader();
        return loader != null ? loader : ControllerScanner.class.getClassLoader();
    }

    /** Result of an indexed lookup, including whether an index resource existed. */
    public record IndexedControllers(boolean indexFound, List<Class<?>> controllers) {
    }

}
