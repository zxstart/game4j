package com.game4j.processor;

import com.game4j.core.annotation.G4JController;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.Filer;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.annotation.processing.SupportedSourceVersion;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.TypeElement;
import javax.tools.FileObject;
import javax.tools.StandardLocation;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.io.Writer;
import java.util.Set;
import java.util.SortedSet;
import java.util.TreeSet;

/** Generates a small class-name index so production startup never needs classpath scanning. */
@SupportedAnnotationTypes("com.game4j.core.annotation.G4JController")
@SupportedSourceVersion(SourceVersion.RELEASE_25)
public final class ControllerIndexProcessor extends AbstractProcessor {
    private static final String INDEX_RESOURCE = "META-INF/game4j/controllers.idx";
    private final SortedSet<String> controllerNames = new TreeSet<>();
    private boolean written;

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        for (Element element : roundEnv.getElementsAnnotatedWith(G4JController.class)) {
            if (element.getKind() != ElementKind.CLASS) {
                processingEnv.getMessager().printMessage(
                        Diagnostic.Kind.ERROR, "@G4JController can only be used on a class", element);
                continue;
            }
            controllerNames.add(((TypeElement) element).getQualifiedName().toString());
        }
        if (roundEnv.processingOver() && !written && !roundEnv.errorRaised()) {
            writeIndex(processingEnv.getFiler());
            written = true;
        }
        return false;
    }

    private void writeIndex(Filer filer) {
        try {
            FileObject file = filer.createResource(StandardLocation.CLASS_OUTPUT, "", INDEX_RESOURCE);
            try (Writer writer = file.openWriter()) {
                writer.write("# Generated by game4j-processor. Do not edit.\n");
                for (String name : controllerNames) {
                    writer.write(name);
                    writer.write('\n');
                }
            }
        } catch (IOException ex) {
            throw new IllegalStateException("Unable to generate " + INDEX_RESOURCE, ex);
        }
    }
}
